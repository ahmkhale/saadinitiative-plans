function sharedSemesterIds(definition) {
  return definition.engineering
    ? ["shared-cfy-science-cfy-science-1", "shared-cfy-science-cfy-science-2", "shared-engineering-common-engineering-common-3", "shared-engineering-common-engineering-common-4"]
    : ["shared-cfy-science-cfy-science-1", "shared-cfy-science-cfy-science-2"];
}

function allRows(definition) {
  return definition.engineering
    ? [...cfyRows, ...engineeringRows, ...definition.rows.map(split)]
    : [...cfyRows, ...definition.rows.map(split)];
}

function buildProposal(definition) {
  const sourceIds = [
    ...sharedSemesterIds(definition),
    ...definition.rows.map((_, index) => `published-level-${index + (definition.engineering ? 5 : 3)}`),
  ];
  const semesters = allRows(definition).map((codes, index) => {
    const level = index + 1;
    const visualCodes = definition.proposalOrder?.[level] ?? codes.filter((code) => code !== definition.summer);
    return {
      id: sourceIds[index],
      sourceSemesterId: sourceIds[index],
      type: "regular",
      courseOrder: [...visualCodes].reverse(),
      placeholders: (definition.placeholders?.[level] ?? []).map(([name, hours], placeholderIndex) => ({
        id: `placeholder-${level}-${placeholderIndex + 1}`,
        ...placeholder(name, hours),
      })),
    };
  });
  semesters.push({
    id: "proposal-summer-1",
    sourceSemesterId: null,
    type: "summer",
    courseOrder: [definition.summer],
    placeholders: [],
  });
  return { enabled: true, title: "الخطة المقترحة", showGuide: true, semesters };
}

function buildPlan(definition) {
  const startLevel = definition.engineering ? 5 : 3;
  const usedCodes = new Set([
    ...definition.rows.flatMap(split),
    ...definition.electives.flatMap((group) => group.courses ?? []).map((entry) => typeof entry === "string" ? entry : entry.code),
  ]);
  const fallbackCourses = Object.fromEntries(
    [...usedCodes].filter((code) => figmaFallbacks[code]).map((code) => [code, figmaFallbacks[code]]),
  );
  return {
    schemaVersion: 1,
    id: definition.id,
    university: "جامعة الملك سعود",
    college: definition.college,
    major: definition.major,
    degree: "البكالوريوس",
    edition: "الطبعة الرابعة",
    release: "إصدار 472.1",
    version: "472.1",
    expectedCredits: definition.expectedCredits,
    sortCourses: "code",
    sharedSemesterSets: definition.engineering ? ["cfy-science", "engineering-common"] : ["cfy-science"],
    semesters: definition.rows.map((codes, index) => semester(startLevel + index, codes)),
    electiveGroups: definition.electives,
    fallbackCourses,
    proposal: buildProposal(definition),
  };
}

function ensureCollege(id, name) {
  const existing = planStore.listColleges().find((college) => college.id === id);
  if (!existing) return planStore.createCollege({ id, name });
  if (existing.name !== name) return planStore.updateCollege(id, { id, name });
  return existing;
}

